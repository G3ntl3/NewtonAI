const CALL_SPACING_MS = 7000; // stays under free-tier ~10 RPM across 7 calls

function sleep(ms) {
  return new Promise((resolve) => setTimeout(resolve, ms));
}

async function runTurn(input) {
  const prompt = buildPrompt(input);
  let raw = '';
  for await (const chunk of streamTurn(prompt)) raw += chunk;
  const cleaned = raw.trim().replace(/^```json\n?/, '').replace(/```$/, '');
  const parsed = tutorTurnSchema.parse(JSON.parse(cleaned));
  return { raw, parsed };
}

function blockTypes(parsed) {
  return parsed.blocks.map((b) => b.type);
}

function chatText(parsed) {
  return parsed.blocks.find((b) => b.type === 'chat')?.payload?.text ?? '';
}

