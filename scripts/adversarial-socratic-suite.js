// scripts/adversarial-socratic-suite.js
//
// PERMANENT adversarial regression suite for the Socratic engine. Each case
// is a real failure mode surfaced during pedagogical tuning this session —
// this suite exists so the next feature (a new block type, a new simulation,
// a prompt tweak) can't silently reopen one of these holes again.
//
// WHY A PLAIN NODE SCRIPT, NOT JEST: @newton/jest-config is currently an
// empty placeholder and `jest` itself is not installed anywhere in this
// repo (checked: not in node_modules, not in any package.json dependency
// list) even though every package's package.json has a `"test": "jest"`
// stub. Installing Jest for real (plus ESM config) is a separate dependency
// decision — the user explicitly chose a plain script instead for this
// suite. This file follows the repo's existing throwaway-diagnostic-script
// pattern (scripts/_*.js), just made permanent and structured as real
// pass/fail assertions instead of console.log inspection.
//
// WHAT IT TESTS: the REAL pipeline — buildPrompt() -> streamTurn() (live
// Gemini call) -> tutorTurnSchema.parse() — asserting on STRUCTURAL facts
// (block types present/absent, assessment enum values, booleans, and the
// actual decideRevealLevel() outcome given the model's assessment). It does
// NOT assert on exact wording, because model output is probabilistic. Where
// a text check is unavoidable it is explicitly marked as a SOFT HEURISTIC.
//
// RATE LIMIT: this hits the live Gemini API once per case (free tier is
// ~10 RPM). Calls are spaced 7s apart. This is a slow integration run, not
// a fast unit suite — expect ~1 minute for all 7 cases.
//
// HOW TO RUN:
//   node scripts/adversarial-socratic-suite.js
//
// Exit code 0 = all cases passed. Exit code 1 = at least one case failed —
// read the FAIL lines; each states expected vs. actual. A failing case is a
// real finding about current engine behavior — do not edit this file to
// make a failure disappear. Fix the engine, or accept and document it.

import '../packages/config/src/dotenv-loader.js';
