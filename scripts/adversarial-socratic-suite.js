async function main() {
  const results = [];

  for (let i = 0; i < cases.length; i++) {
    const c = cases[i];
    process.stdout.write(`\nRunning: ${c.name}\n`);
    try {
      const checks = await c.run();
      const failed = checks.filter(([ok]) => !ok);
      if (failed.length === 0) {
        console.log(`  PASS`);
        results.push({ name: c.name, pass: true });
      } else {
        console.log(`  FAIL`);
        for (const [, msg] of failed) console.log(`    - ${msg}`);
        results.push({ name: c.name, pass: false, failures: failed.map(([, msg]) => msg) });
      }
    } catch (err) {
      console.log(`  ERROR: ${err.message}`);
      results.push({ name: c.name, pass: false, failures: [`threw: ${err.message}`] });
    }

    if (i < cases.length - 1) await sleep(CALL_SPACING_MS);
  }

  console.log('\n=== SUMMARY ===');
  for (const r of results) console.log(`${r.pass ? 'PASS' : 'FAIL'} — ${r.name}`);
  const failCount = results.filter((r) => !r.pass).length;
  console.log(`\n${results.length - failCount}/${results.length} passed.`);
  process.exit(failCount > 0 ? 1 : 0);
}

main();
